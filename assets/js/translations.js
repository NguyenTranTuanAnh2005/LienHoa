function switchLanguage(lang) {
  // Save to localStorage so language persists across pages
  localStorage.setItem('lang', lang);

  // Switch all elements having data-lang
  document.querySelectorAll('[data-lang]').forEach(el => {
    const key = el.getAttribute('data-lang');
    if (translations[lang][key]) {
      if (el.tagName.toLowerCase() === "input" || el.tagName.toLowerCase() === "textarea") {
        el.setAttribute('placeholder', translations[lang][key]);
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });

  // Switch all dynamic database elements having data-translate-text
  document.querySelectorAll('[data-translate-text]').forEach(el => {
    const originalText = el.getAttribute('data-original-text') || el.textContent.trim();
    if (!el.hasAttribute('data-original-text')) {
      el.setAttribute('data-original-text', originalText);
    }
    const currentLangDict = translations[lang];
    if (currentLangDict && currentLangDict[originalText]) {
      el.textContent = currentLangDict[originalText];
    } else if (lang === 'VI') {
      el.textContent = originalText;
    }
  });

  // Switch page title
  document.title = translations[lang].pageTitle;
  // Switch document language
  document.documentElement.lang = lang.toLowerCase();

  // Update language toggle button if it exists
  const langLabel = document.querySelector('#langLabel');
  if (langLabel) langLabel.textContent = lang;
  const langSwitch = document.querySelector('#langSwitch');
  if (langSwitch) langSwitch.checked = (lang === 'EN');
}

// Ensure language persists smoothly on page load
window.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('lang') || 'VI';
  switchLanguage(savedLang);
});
